#!/usr/bin/env python3
"""Generate the tiny instrument fixtures the timidity harnesses use (committed output, so build.sh
never needs this script): tiny.sf2 (SoundFont 2, one 8-bit-ish sine sample, melodic + drum preset),
tiny.pat (GUS GF1 patch, one sample), song.mid (program change, a note, a drum note), and
fixtures.h (the same bytes as C arrays)."""
import math, struct, sys, os

def chunk(cid, data):
    if len(data) & 1: data += b"\0"
    return cid + struct.pack("<I", len(data)) + data

def lst(kind, body):
    return chunk(b"LIST", kind + body)

def name20(s):
    return s.encode().ljust(20, b"\0")

def sf2():
    n = 256
    smp = b"".join(struct.pack("<h", int(12000 * math.sin(2 * math.pi * i / 32))) for i in range(n))
    smp += b"\0" * 92  # 46 zero samples after each sample (SF2 spec)
    info = lst(b"INFO", chunk(b"ifil", struct.pack("<HH", 2, 1)) + chunk(b"isng", b"EMU8000\0") + chunk(b"INAM", b"tiny\0\0"))
    sdta = lst(b"sdta", chunk(b"smpl", smp))
    phdr = (name20("mel") + struct.pack("<HHHIII", 0, 0, 0, 0, 0, 0)
            + name20("drum") + struct.pack("<HHHIII", 0, 128, 1, 0, 0, 0)
            + name20("EOP") + struct.pack("<HHHIII", 0, 0, 2, 0, 0, 0))
    pbag = struct.pack("<HH", 0, 0) + struct.pack("<HH", 1, 0) + struct.pack("<HH", 2, 0)
    pmod = b"\0" * 10
    pgen = struct.pack("<HH", 41, 0) + struct.pack("<HH", 41, 0) + struct.pack("<HH", 0, 0)
    inst = name20("inst") + struct.pack("<H", 0) + name20("EOI") + struct.pack("<H", 1)
    ibag = struct.pack("<HH", 0, 0) + struct.pack("<HH", 2, 0)
    imod = b"\0" * 10
    igen = struct.pack("<Hh", 54, 1) + struct.pack("<HH", 53, 0) + struct.pack("<HH", 0, 0)  # loop, sampleID
    shdr = (name20("sine") + struct.pack("<IIIIIBbHH", 0, n, 32, n - 32, 22050, 69, 0, 0, 1)
            + name20("EOS") + struct.pack("<IIIIIBbHH", 0, 0, 0, 0, 0, 0, 0, 0, 0))
    pdta = lst(b"pdta", chunk(b"phdr", phdr) + chunk(b"pbag", pbag) + chunk(b"pmod", pmod) + chunk(b"pgen", pgen)
               + chunk(b"inst", inst) + chunk(b"ibag", ibag) + chunk(b"imod", imod) + chunk(b"igen", igen) + chunk(b"shdr", shdr))
    return chunk(b"RIFF", b"sfbk" + info + sdta + pdta)

def pat():
    n = 256
    hdr = bytearray(239)
    hdr[0:22] = b"GF1PATCH110\0ID#000002\0"
    hdr[22:22 + 13] = b"tiny fixture\0"
    hdr[82] = 1    # instruments
    hdr[151] = 1   # layers
    hdr[198] = 1   # samples
    data = bytes((int(100 * math.sin(2 * math.pi * i / 32)) & 0xff) for i in range(n))
    s = b"sine\0\0\0" + b"\0"
    s += struct.pack("<iiiHiiiH", n, 32, n - 32, 22050, 8176, 12543853, 440000, 0)
    s += b"\x07"                                   # balance
    s += bytes([0x3f, 0x3f, 0x3f, 0x3f, 0x3f, 0x3f, 250, 250, 250, 200, 0, 0])  # envelope rate/offset
    s += b"\0" * 6                                 # tremolo/vibrato
    s += b"\x04"                                   # modes: looping, 8-bit signed
    s += b"\0" * 40
    assert len(s) == 96
    return bytes(hdr) + s + data

def mid():
    trk = bytes([0, 0xC0, 0, 0, 0x90, 0x3C, 0x64, 0x60, 0x80, 0x3C, 0, 0, 0x99, 0x24, 0x64, 0x60, 0x89, 0x24, 0, 0, 0xFF, 0x2F, 0])
    return b"MThd" + struct.pack(">IHHH", 6, 0, 1, 0x60) + b"MTrk" + struct.pack(">I", len(trk)) + trk

def voc():
    pcm = bytes((128 + int(100 * math.sin(2 * math.pi * i / 32))) & 0xff for i in range(512))
    hdr = b"Creative Voice File\x1a" + struct.pack("<HHH", 26, 0x010A, 0x1129)
    blk = bytes([1]) + struct.pack("<I", len(pcm) + 2)[:3] + bytes([256 - 1000000 // 11025, 0]) + pcm
    return hdr + blk + b"\0"

def aiff():
    n = 512
    pcm = b"".join(struct.pack(">h", int(12000 * math.sin(2 * math.pi * i / 32))) for i in range(n))
    rate = bytes([0x40, 0x0D, 0xAC, 0x44] + [0] * 6)  # 80-bit extended 22050
    be = lambda cid, d: cid + struct.pack(">I", len(d)) + d  # IFF chunks are big-endian
    comm = be(b"COMM", struct.pack(">hIh", 1, n, 16) + rate)
    ssnd = be(b"SSND", struct.pack(">II", 0, 0) + pcm)
    return be(b"FORM", b"AIFF" + comm + ssnd)

def carr(name, b):
    body = ",".join(str(x) for x in b)
    return f"static const unsigned char {name}[{len(b)}] = {{{body}}};\n"

out = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
files = {"tiny.sf2": sf2(), "tiny.pat": pat(), "song.mid": mid(), "tone.voc": voc(), "tone.aiff": aiff()}
for k, v in files.items():
    open(os.path.join(out, k), "wb").write(v)
with open(os.path.join(out, "fixtures.h"), "w") as f:
    f.write("/* generated by gen_fixtures.py; do not edit */\n")
    f.write(carr("fixture_sf2", files["tiny.sf2"]) + carr("fixture_pat", files["tiny.pat"]) + carr("fixture_mid", files["song.mid"]))
